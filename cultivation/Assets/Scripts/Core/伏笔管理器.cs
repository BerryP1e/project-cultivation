using UnityEngine;
using UnityEngine.SceneManagement;

/// <summary>
/// **两大伏笔的"发酵"** —— 用户第四阶段原文：
/// 「**灵田异常灵气**、**镇妖塔妖力共鸣** 两大伏笔持续发酵，
/// 为后续「灵田异变、镇妖塔解封、宗门秘境开启」预留空间」。
///
/// 之前只有两句台词（阶段37 / 38 的对话），**说过就完了**；这一版把它做成
/// **按天/按次逐级推进的"异象等级"**（0~3 级，每级一句台词 + 一层世界表现，
/// 表现在 <see cref="伏笔表现"/>）。
///
/// ## 两条线各自的起点与节奏
///
/// | 线 | 起点（对话标记） | 节奏（每级） | 满级 |
/// |---|---|---|---|
/// | 灵田异常灵气 | `q_伏笔_灵田异样`（阶段37 到达洞府） | **每 2 天**一级（第 2 级要第 4 天、第 3 级要第 6 天） | 3 |
/// | 镇妖塔妖力共鸣 | `q_主线_塔已讲解`（阶段33 师父讲完塔的规矩） | **每进塔 2 次**一级 | 3 |
///
/// 【为什么塔线起点用阶段33 而不是阶段38】阶段38「塔中的共鸣」要**炼气五层**，
/// 是**长线钩子**、正常流程很久都碰不到；而伏笔要"持续发酵"就得从玩家**开始刷塔**
/// 那一刻起有反馈 ⇒ 起点放在塔的规矩讲完（阶段33），
/// **阶段38 的台词改成这条线的"正式揭示"**（两边不冲突：一条是机制、一条是剧情）。
///
/// 【为什么要"起点天/起点次数"这两个锚点】等级不能只按"天数 % N"算 ——
/// 那样玩家在阶段37 之前攒的天数会**一次性追补**成满级（进洞府瞬间三级异象）。
/// 锚点让"发酵"从**拿到标记的那一天**开始数。
/// </summary>
public class 伏笔管理器 : MonoBehaviour
{
    public const int 满级 = 3;
    public const string 灵田标记 = "q_伏笔_灵田异样";
    public const string 塔标记 = "q_主线_塔已讲解";

    static 伏笔管理器 实例;
    public static 伏笔管理器 取() => 实例;

    public int 灵田等级 { get; private set; }
    public int 塔等级 { get; private set; }

    [Tooltip("灵田伏笔：第 N 级要隔 N × 这个天数")]
    public int 灵田每级天数 = 2;
    [Tooltip("塔伏笔：第 N 级要 N × 这么多次进塔")]
    public int 塔每级次数 = 2;
    public string 塔场景名 = "Demon-Suppressing Tower";

    /// <summary>等级变化（升一级）时发一次</summary>
    public event System.Action 变化;

    int 灵田起点天 = -1;
    int 进塔次数;
    bool 上次在塔里;

    /// <summary>每级一句（索引 1~3 有效）。口吻是"主角心里咯噔一下"，不是说明文。</summary>
    public static readonly string[] 灵田台词 =
    {
        "",
        "洞府灵田：土里的灵气比昨天活泛了些……是错觉吗。",
        "洞府灵田：叶尖泛着不该有的光，掐下来看又什么都没有。",
        "洞府灵田：夜里经过，田垄底下像是有什么在呼吸。",
    };

    public static readonly string[] 塔台词 =
    {
        "",
        "镇妖塔：塔身偶尔震一下，很轻，像有什么在里头翻身。",
        "镇妖塔：那股妖力开始应和你的脚步，一进塔就压得胸口发闷。",
        "镇妖塔：共鸣越来越清楚 —— 塔里封着的东西，认得你。",
    };

    void Awake() { 实例 = this; }

    void OnDestroy() { if (实例 == this) 实例 = null; }

    void Update()
    {
        // 读档进来的等级挂在 `SaveSystem` 上（理由同 日常循环.Update）
        if (SaveSystem.有挂起的伏笔)
        {
            int 田, 塔;
            SaveSystem.取挂起的伏笔(out 田, out 塔);
            导入(田, 塔);
            Debug.Log("[伏笔] 读档恢复：灵田 " + 田 + " 级 / 塔 " + 塔 + " 级");
        }

        推进灵田();
        推进塔();
    }

    void 推进灵田()
    {
        if (灵田等级 >= 满级) return;
        if (!任务触发区.有全部标记(灵田标记)) return;

        var t = 时间管理器.取();
        if (t == null) return;

        if (灵田起点天 < 0) { 灵田起点天 = t.当前天数; return; }

        if (t.当前天数 - 灵田起点天 >= 灵田每级天数 * (灵田等级 + 1)) 升灵田();
    }

    void 推进塔()
    {
        var 场景 = SceneManager.GetActiveScene().name;
        bool 在塔 = !string.IsNullOrEmpty(塔场景名) && 场景 == 塔场景名;
        if (在塔 && !上次在塔里)
        {
            进塔次数++;
            Debug.Log("[伏笔] 第 " + 进塔次数 + " 次进塔（塔共鸣等级 " + 塔等级 + "/" + 满级 + "）");
        }
        上次在塔里 = 在塔;

        if (塔等级 >= 满级) return;
        if (!任务触发区.有全部标记(塔标记)) return;
        if (进塔次数 >= 塔每级次数 * (塔等级 + 1)) 升塔();
    }

    void 升灵田()
    {
        灵田等级 = Mathf.Min(满级, 灵田等级 + 1);
        Debug.Log("[伏笔] 灵田异常灵气 → " + 灵田等级 + " 级：" + 灵田台词[灵田等级]);
        ToastUI.提示(灵田台词[灵田等级], 3.2f);
        变化?.Invoke();
    }

    void 升塔()
    {
        塔等级 = Mathf.Min(满级, 塔等级 + 1);
        Debug.Log("[伏笔] 镇妖塔妖力共鸣 → " + 塔等级 + " 级：" + 塔台词[塔等级]);
        ToastUI.提示(塔台词[塔等级], 3.2f);
        变化?.Invoke();
    }

    // ============================================================ 存档

    public void 导出(out int 田, out int 塔)
    {
        田 = 灵田等级;
        塔 = 塔等级;
    }

    public void 导入(int 田, int 塔)
    {
        灵田等级 = Mathf.Clamp(田, 0, 满级);
        塔等级 = Mathf.Clamp(塔, 0, 满级);
        变化?.Invoke();
    }
}
