using UnityEngine;

/// <summary>
/// **一块田地的状态**（可存档）。
///
/// 【2026-10-01 第二次重构】用户要求灵田**不再固定在场景里**，而是自己在洞府里摆：
/// > 「现在的灵田是固定位置的，我希望个人洞府是能够自定义的，包括自由选择灵田块的位置……
/// >   在背包中找到灵田开拓令……鼠标会变成一块待摆放的半透明的灵田，
/// >   可以在整个洞府中有地面的有空间的地方任意的摆放。」
/// > 「我看你还做了待开发的灵田，现在把待开发的灵田的模型转变为**待种植**的灵田模型。」
///
/// 所以这一版：
///   · **"荒地"这个状态没有了** —— 玩家放下的一块地**就是待种植的熟地**，
///     不再有"先开拓荒地、再种"那一步（开拓 = 从背包里把地摆下来）；
///   · 每块地自己记 **位置 + 朝向**（玩家摆的），所以它才存得下、重建得出来。
///
/// 【它只管数据】外观在 <c>灵田地块外观</c>、交互在 <c>灵田地块</c>、
/// 摆放态在 <c>灵田摆放器</c>、界面在 <c>灵田地块界面</c> / <c>灵田界面</c>。
/// 这样存档只碰这一个类。
///
/// ⚠️ 本类**同时就是存档类型**（`SaveData.灵田地块` 是 `List&lt;灵田地块状态&gt;`）——
/// 字段都必须是 `JsonUtility` 支持的类型（string / float / int / Vector3），
/// **加字段时别加 Dictionary、接口、属性**，否则存档静默丢失。
/// </summary>
[System.Serializable]
public class 灵田地块状态
{
    // ============================================================ 摆在哪

    /// <summary>世界坐标（玩家摆放时定的）</summary>
    public Vector3 位置 = Vector3.zero;

    /// <summary>
    /// 朝向档，**0~7**，每档 45°。
    /// 【为什么是"档"而不是直接存角度】用户要求「摆放中的灵田可以旋转 **8 个朝向**」，
    /// 档位化之后：吸附判定只要比较整数（同档才能吸附）、存档也不会因为浮点误差漂移。
    /// </summary>
    public int 朝向档 = 0;

    /// <summary>朝向角度（度）</summary>
    public float 朝向角度 => 朝向档 * 45f;

    // ============================================================ 状态

    /// <summary>**这一块地自己的品阶**。决定能种什么（灵植有品阶门槛）、产量、生长速度</summary>
    public 灵田品阶 品阶 = 灵田品阶.一阶下品;

    /// <summary>种着的灵植 id。空 = **待种植**</summary>
    public string 作物id = "";

    /// <summary>已经生长了多少**游戏日**（按这块地的生长倍率算过的等效值）</summary>
    public float 已生长天数 = 0f;

    // ============================================================ 查询

    /// <summary>空着、等着种（放下就是这种状态）</summary>
    public bool 待种植 => string.IsNullOrEmpty(作物id);

    public 灵植定义 植 => 灵植库.取(作物id);

    /// <summary>
    /// 成熟了吗。
    /// **成熟天数是灵植自己的，不乘品阶倍率** —— 品阶影响的是"长得快不快"，
    /// 那部分在累计 <see cref="已生长天数"/> 的时候就已经乘进去了。
    /// </summary>
    public bool 已成熟
    {
        get { var d = 植; return d != null && 已生长天数 >= d.成熟天数; }
    }

    /// <summary>生长进度 0~1</summary>
    public float 进度
    {
        get
        {
            var d = 植;
            if (d == null || d.成熟天数 <= 0f) return 0f;
            return Mathf.Clamp01(已生长天数 / d.成熟天数);
        }
    }

    /// <summary>还需要多少游戏日成熟（已成熟 = 0）</summary>
    public float 剩余天数
    {
        get
        {
            var d = 植;
            if (d == null || 已成熟) return 0f;
            return Mathf.Max(0f, d.成熟天数 - 已生长天数);
        }
    }

    /// <summary>
    /// 外观阶段：**0 待种植 · 1 幼苗 · 2 成长 · 3 成熟**。
    /// （比上一版少一档"荒"，因为荒地已经不存在了。）
    /// </summary>
    public int 阶段
    {
        get
        {
            if (待种植) return 0;
            if (已成熟) return 3;
            return 进度 < 0.5f ? 1 : 2;
        }
    }

    /// <summary>阶段名（给信息牌用）</summary>
    public string 阶段名
    {
        get
        {
            switch (阶段)
            {
                case 0: return "待种植";
                case 1: return "幼苗";
                case 3: return "已成熟";
                default: return "成长中";
            }
        }
    }

    public void 清空作物()
    {
        作物id = "";
        已生长天数 = 0f;
    }

    // ============================================================ 升级的代价
    //
    // 需求原文：「灵田可随你的修为提升、宗门贡献升级」。
    // 用户 2026-10-01 纠正过：**不消耗灵草**，消耗的是**在宗门贡献处兑换的道具**
    // （`item_lingtian_ling` 灵田升阶令）。贡献系统做出来后只要把那个道具挂进兑换商店，
    // **本文件一行都不用改**。在贡献就绪之前，这道具可以用 F1 面板发放。

    /// <summary>升到下一阶要几张升阶令：当前 1 阶要 3 张、2 阶要 4 张……</summary>
    public static int 升阶令张数(灵田品阶 当前) => 2 + (int)当前;

    /// <summary>升到下一阶的境界等级门槛：和「炼气三层」那类门槛同一条尺子</summary>
    public static int 需要境界等级(灵田品阶 当前) => 3 * (int)当前;

    public bool 已满阶 => 品阶 >= 灵田品阶.三阶上品;

    // 注：「能不能种这种灵植」的完整判定在 `灵田.能种(i, 灵植id, out 原因)` ——
    // 它还要查背包里的种子，而种子是运行时状态，不该塞进这个纯数据类。
}
