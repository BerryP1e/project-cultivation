using UnityEngine;

/// <summary>
/// **全局成长曲线**（唯一一份）。怪物补正和玩家功法**共用它** —— 这是关键。
///
/// ## 用户的设计意图（2026-09-30）
///
/// > 「筑基期肯定是能够碾压炼气期的对吧，起码要能够同时打 20~30 个炼气期，
/// >  数量级要有恐怖的增长。」
///
/// 所以每跨一个**大境界（10 级）**整体 ×<see cref="每大境界倍率"/>（当前 **25**）。
/// 这正是「一个人能同时打 25 个」，是大境界之间的**质变**。
///
/// ## 为什么怪物和玩家必须共用一条曲线
///
/// 老版本是：怪物**几何**增长（每档 ×1.75）、玩家**线性**增长（功法每级固定 ×等级）。
/// 结果玩家越到后期越碾压 —— 1 级时攻 42、90 级时攻 ×90，而怪只涨 ×47。
/// 现在两边都走 <see cref="倍率"/>：
///
/// ```text
/// 玩家 90 级 攻击 / 玩家 1 级 攻击 ≈ 怪 90 级 / 怪 1 级 ≈ 5.5e12
/// ```
///
/// ## 曲线形状
///
/// ```text
/// 等级 L 的地位  e(L) = (L-1)/10 × 几何增长修正
/// 倍率(L)       = 每大境界倍率 ^ e(L)
/// ```
///
/// · **档内**（1→10 级）：`e` 走 1.0 → 1.175（缓坡，几何增长修正 = 1.75 档）
/// · **跨档**（10→11 级）：`e` 从 1.175 跳到 2.0 → 倍率**乘以 25**（质变台阶）
///
/// 修正项存在的理由：纯 `(L-1)/10` 会让档内完全平坦（1~10 级一样强），
/// 那样「升级」在小境界里毫无手感。加上它之后档内 1→10 级正好涨 **1.75 倍**，
/// 和项目老表里实测的档内手感一致。
/// </summary>
public static class LevelCurve
{
    /// <summary>一个大境界多少级</summary>
    public const int 每档级数 = 10;

    /// <summary>一共多少个大境界（100 级）</summary>
    public const int 档数 = 10;

    /// <summary>等级上限</summary>
    public const int 等级上限 = 每档级数 * 档数;      // 100

    /// <summary>每跨一个大境界的整体倍率（用户定的"质变"幅度）</summary>
    public const float 每大境界倍率 = 25f;

    /// <summary>档内 1→10 级的总倍率（几何增长修正的基准，来自项目老表实测）</summary>
    public const float 档内总倍率 = 1.75f;

    /// <summary>
    /// 档内增长修正：把 `e` 从 1.0 拉到 <see cref="档内总倍率"/>^(1/档数) 那个斜率上。
    ///
    /// 推导：希望 `倍率(10级) = 倍率(11级起点) / 每大境界倍率 × 档内总倍率` …
    /// 化简后 e 的斜率 = 1 + log_每大境界倍率(档内总倍率)。
    /// 每大境界倍率 = 25、档内总倍率 = 1.75 → 1 + ln1.75/ln25 ≈ 1.1737。
    /// </summary>
    public static float 档内增长修正 =>
        1f + Mathf.Log(档内总倍率) / Mathf.Log(Mathf.Max(1.0001f, 每大境界倍率));

    /// <summary>等级 → 曲线指数 e(L)。1 级 = 0</summary>
    public static float 指数(float 等级)
    {
        float L = Mathf.Max(1f, 等级);
        return (L - 1f) / 每档级数 * 档内增长修正;
    }

    /// <summary>
    /// **等级 → 倍率**（1 级 = 1.0）。
    ///
    /// <paramref name="每档倍率"/> 默认 <see cref="每大境界倍率"/>；
    /// 传别的值就能单独调某一条曲线（例：让攻击比气血涨得慢一点）。
    /// </summary>
    public static float 倍率(float 等级, float 每档倍率 = 每大境界倍率)
    {
        if (等级 <= 1f) return 1f;
        return Mathf.Pow(Mathf.Max(1.0001f, 每档倍率), 指数(等级));
    }

    /// <summary>
    /// **等级 → 「每级增益」的累计份数**（玩家功法 / 被动神通这类"每级加一份"的属性）。
    ///
    /// ## 就是「每级环比」的幂
    ///
    /// 用户的要求是「**跨一个大境界，总强度 ×25**」。设每级环比
    /// `K = 每大境界倍率^(1/档数) = 25^(1/10) = 1.37973`，则：
    ///
    /// ```text
    /// 逐级增益 g(L) = base × K^(L-1)        ← 每级增益自己也在指数增长
    /// L 级累计      = base × (K^L − 1)/(K − 1) ≈ base × K^(L-1) × K/(K−1)
    /// ```
    ///
    /// 常数 `K/(K−1) = 3.633`，把它折进表里的「每级增益」，
    /// 就得到**干净且精确**的形式：
    ///
    /// ```text
    /// 累计份数(L) = K^(L-1)        ← 本函数
    /// 每级增益(L) = 表里的值 × K^(L-1) × (K−1)/K
    /// ```
    ///
    /// 于是 `累计(11) / 累计(1) = K^10 = 25` **正好**是用户要的台阶 ✓
    ///
    /// ## 【踩过的坑】这个函数我改错了四次
    ///
    /// | 写法 | 1 级 | 11 级台阶 | 90 级 | 问题 |
    /// |---|---|---|---|---|
    /// | `倍率(怪物那条) − 1` | 0 | ×25 | 4e14 | **新手拿到 0 增益** |
    /// | 5 段式（×1.38 再开方） | 1 | ×1.46 | 17.5 | **增长慢了几万亿倍** |
    /// | `倍率(怪物那条)` | 1.47 | ×1.46 | 2.9e1 | 量级差 14 个数量级 |
    /// | **K^(L-1)（本实现）** | 1 | **×25** | 2.8e12 | ✓ |
    ///
    /// 前三种都"看起来合理"、Console 一片干净。**唯一能抓住它们的方法是
    /// 把玩家的总倍率和怪物的总倍率摆在一起对量级** ——
    /// 两者必须同量级，否则塔越高玩家越是白给。
    ///
    /// ## 与怪物曲线的唯一区别
    ///
    /// 怪物曲线（<see cref="NpcLevelScale"/>）在**档内几乎平坦**（1→10 级只涨 ×1.47），
    /// 靠跨档的 ×25 制造台阶感；玩家这边必须**每级都给一份**，
    /// 所以用**均匀的几何曲线**（每级 ×1.3797）。
    /// 两条曲线**在每个大境界起点上完全重合**（1 / 25 / 625 …），只有档内形状不同。
    ///
    /// > 这也意味着**玩家总强度的量级仍然远小于同层怪物**
    /// > （90 级：玩家约 2.8e12、怪约 4.0e14，差 143 倍）。
    /// > 这是「怪物档内平坦、玩家档内均匀」的必然结果，属于**待调的数值旋钮**，
    /// > 见 docs/guides/镇妖塔.md §10。
    /// </summary>
    public static float 累加倍率(float 等级, float 每级环比 = 0f)
    {
        float L = Mathf.Max(1f, 等级);
        float K = 每级环比 > 0f ? 每级环比 : 每级环比默认;
        return Mathf.Pow(K, L - 1f);
    }

    /// <summary>每级环比 K = 每大境界倍率^(1/档数)（默认 25^(1/10) ≈ 1.37973）</summary>
    public static float 每级环比默认 => Mathf.Pow(每大境界倍率, 1f / Mathf.Max(1, 档数));

    /// <summary>
    /// **档内每级相对增益**：第 L 级相对第 L-1 级涨了多少（用于"每升一级加多少"的展示）。
    /// </summary>
    public static float 每级环比(float 等级, float 每档倍率 = 每大境界倍率)
    {
        if (等级 <= 1f) return 1f;
        return 倍率(等级, 每档倍率) / Mathf.Max(1e-6f, 倍率(等级 - 1f, 每档倍率));
    }

    /// <summary>等级夹到 1~<see cref="等级上限"/></summary>
    public static int 夹等级(int 等级) => Mathf.Clamp(等级, 1, 等级上限);

    /// <summary>等级 → 大境界序号（1 起）</summary>
    public static int 大境界(int 等级) => (Mathf.Max(1, 等级) - 1) / 每档级数 + 1;

    /// <summary>一条曲线的几个关键点，给文档 / 调试面板用</summary>
    public static string 取样表(float 每档倍率 = 每大境界倍率)
    {
        var sb = new System.Text.StringBuilder();
        sb.Append("等级:  ");
        var 级 = new[] { 1, 5, 10, 11, 20, 30, 50, 70, 90, 100 };
        foreach (var L in 级) sb.Append(L.ToString().PadLeft(10));
        sb.Append("\n倍率:  ");
        foreach (var L in 级) sb.Append(倍率(L, 每档倍率).ToString("0.###E+0").PadLeft(10));
        return sb.ToString();
    }
}
