using UnityEngine;

/// <summary>任务分类（用户 2026-09-26：主线 / 支线 / 悬赏）</summary>
public enum 任务类型 { 主线, 支线, 悬赏 }

/// <summary>子任务的完成条件</summary>
public enum 任务条件
{
    无,        // 接了就立刻算完成（用来串"过场"阶段）
    提交物品,  // 背包里有够数量的物品 → 交了就算完成（会扣掉）
    击杀,      // 目标npcId 的那个 NPC 死掉（留空 = 任意 NPC 死一个）
    到达,      // 玩家走到 坐标 半径 以内
    对话,      // 和 NPC 说完某一段对话（对话id 留空 = 这段里任意一段）
    等待秒数,  // ★ 主线用：进入这一阶段后**等 N 秒**自动完成（"停留2s""等候60s"都用它）
    NPC到位    // ★ 目标npcId 的 NPC 走到「坐标」附近才算完成
               //   （四幕：大师兄飞回来，要**到位之后**再跳对话，而不是时间一到就跳）
    ,落点结束   // ★ 玩家落点流程结束（「移动玩家」/「移动玩家且黑幕」把主角放到位）才算完成，
               //   用来让下一阶段等到落点处理完 —— 黑幕结束时主角刚好站在该站的地方
    ,黑幕落下完成 // ★ 黑幕的**阶梯淡入**跑完才算完成（配 动作=落黑幕 用）
                 //   否则 条件=无 会在下一帧就推进，把还没淡完的黑幕直接收掉
    ,灵田已种植   // ★ 灵田里**已经种下东西**的地块数 ≥ `数量`（灵田教学"种下第一颗种子"靠它验真）
    ,境界等级     // ★ 玩家境界等级 ≥ `数量`（例：镇妖塔准入 = 炼气三层 = 3）
    ,炼过丹       // ★ **已经炼成过** ≥ `数量` **种**丹药（数 `炼成_` 标记，见 炼丹炉.炼成过的种类数）。
                  //   任意一种丹药都算 —— 用户 2026-10-02 的原话：
                  //   「走近丹房，也不是炼某一种丹药，我这里的意思是任意一种丹药就可以了」
                  //   ⚠️ 判据是 `炼成_` 而**不是** `丹方_`：后者任务表阶段24 也会打（一次给 4 张丹方），
                  //      拿它当判据会让阶段27 一进去就"已经炼过丹"了（实测踩过）。
    ,在场景       // ★ 玩家**此刻就在「场景名」写的那个场景里**就算完成。
                  //   专治"目标就是走进那道光 / 回到洞府"这类阶段：
                  //   用 `到达` 要靠坐标（两个场景的坐标是两套空间，容易误判），
                  //   用 `对话` 又变成"必须先跟某人说句话"（用户 2026-10-02 明确否掉了这个耦合：
                  //   「不能作为大师兄模型是否在洞府中加载的关键」）。填「场景名」那一列即可。
}

/// <summary>阶段开始时要调度的 NPC 动作</summary>
public enum 任务动作
{
    无,
    播动画,     // 动作参数 = 状态名（如 swagger / Attack1 / Yufeng_Idle）
    攻击玩家,   // 好感度压到敌对 → 自动锁定玩家开打
    销毁,       // 直接销毁目标 NPC
    走向,       // ★ 走到「坐标」（带行走动画；速度见 动作速度）
    飞到,       // ★ 御风飞过去：升空 → 前进（同时位移）→ 到点悬停（前进状态名见 动作参数）
    处决,       // ★ 直接把目标 NPC 打死（三幕大师兄一刀劈野猪：配合 闪白）
    镜头看目标, // ★ 镜头平滑推向目标 NPC（时长见 镜头时长）
    镜头回玩家, // ★ 镜头平滑回到玩家身上
    生成NPC,    // ★ 生成一个 NPC：**动作参数 = 预制体资源路径**（如 `NPC/Demon/YeZhu/YeZhu`），位置 = `坐标`
    播放对话,   // ★ 强制弹一段对话（不用玩家按 F）：说话人列 / 台词列 / 情绪列（三幕主角惊叫、四幕大师兄招募都用它）
    黑幕字幕,   // ★ 黑幕白字：台词列写词，多行用 | 分隔；逐字打出后自动收幕
    落黑幕,     // ★ **只落黑幕、不打字**（台词列留空），并可同时登记玩家落点。
                 //   四幕「和仙人说完话 → 淡入黑幕 → 黑屏切场景」用它：
                 //   黑幕要在**切场景之前**盖上，否则切换那一帧会闪、进场景后
                 //   主角被拉到策划落点的过程也会被看见。
                 //   淡入档数取「淡入档数」列；等待秒 = 等它淡完的时间。台词列若填了字也会打。
    闪白,       // ★ 黑屏白屏闪一下（三幕大师兄一刀劈野猪：配合 处决）
    切换场景,   // ★ 切到「场景名」列写的场景（单场景加载，任务进度靠 跨场景数据 带过去）
    移动玩家,   // ★ 把玩家挪到「坐标」（四幕切到宗门后把主角放到大师兄旁边）
    移动玩家且黑幕, // ★ 同「移动玩家」，但**同一帧先落黑幕**当遮罩 ——
                    //   用来盖住「切场景 → 主角被拉到策划落点」这段拉扯（四幕第 3 阶段）。
                    //   台词列就是黑幕上要打的字。
    接取任务,   // ★ 接取另一个任务：**动作参数 = 要接取的任务id**（三幕演完自动开四幕就靠它）
    确保NPC,    // ★ 目标 NPC 不在场就重建：**动作参数 = 预制体路径**，位置 = `坐标`
                //   （四幕：大师兄是任务生成的场景内对象，玩家在「等候 60 秒」期间切了场景
                //     就会把它销毁，后面的「飞到」找不到目标 → 静默失败、大师兄不再出现。
                //     放在「飞到」之前补一个它即可）
    推进天数    // ★ **把游戏内时间往前推一天**（固定 1 天）。
                //   用来演「过了一夜 / 次日清晨」——以前是用 `等待秒数=3` 假装过夜，
                //   时间系统根本没动，于是玩家不会拿到新的一天那份修炼机会，纪年也不变。
                //   ★ **台词非空时顺便打一段黑幕字幕**（2026-10-02 加）：
                //     用户报「过了一夜，也没有真的过了一夜，那个翌日、太虚宗的黑幕出场时机也有问题」
                //     —— 天数在偷偷跳、画面上什么都没有，而那次「翌日」黑幕被排在
                //     大师兄早上那段话**之后**，顺序是反的。任务表「动作」只有一列，
                //     所以让这个动作顺手把「过夜」那一幕也演了（参数见 任务管理器.执行动作）。
}

/// <summary>
/// **任务的一个子任务（阶段）** —— 一行 = 一个阶段，对应 `Assets/Data/Tables/任务表.csv`。
///
/// 设计（对应用户的要求）：
///   · 同一个 <see cref="任务id"/> 下的阶段按 <see cref="阶段"/> **从小到大顺序推进**，
///     当前阶段完成才会把下一个阶段设为"当前"（"只有当子任务完成时，才会触发下一个"）。
///   · 完成条件有四种：提交材料 / 击杀目标 / 到达某地 / 和 NPC 完成某段对话。
///   · 任务状态用**标记**（<see cref="接取加标记"/> / <see cref="完成加标记"/>）和对话系统打通 ——
///     对话表里的「需要标记 / 排除标记」就能让任务出现新的回答（复用对话系统那套条件）。
///   · 阶段开始时可以调度 NPC：<see cref="动作"/>（播动画 / 攻击玩家 / 销毁）+ 目标 id + 参数。
///   · 完成阶段可以发物品奖励：<see cref="奖励物品"/>，写法同「背包物品」列（`物品id:数量|物品id:数量`）。
/// </summary>
[CreateAssetMenu(fileName = "任务阶段_", menuName = "修仙/任务/阶段", order = 20)]
public class QuestDefinition : ScriptableObject
{
    [Header("归属")]
    public string id = "";              // 这一行的唯一 id
    public string 任务id = "";          // 同一串阶段共用一个任务id
    public string 任务名 = "";
    public 任务类型 类型 = 任务类型.支线;

    [Header("阶段")]
    [Min(1)] public int 阶段 = 1;
    public string 阶段名 = "";

    [TextArea(2, 6)]
    [Tooltip("任务面板里显示的说明")]
    public string 说明 = "";

    [Header("完成条件")]
    public 任务条件 条件 = 任务条件.无;

    [Tooltip("条件=提交物品 时：要交的物品 id")]
    public string 物品id = "";

    [Tooltip("条件=提交物品 时：要交几个")]
    [Min(1)] public int 数量 = 1;

    [Tooltip("条件=击杀 时：目标 NPC 的 NpcDefinition.id。**留空 = 任意 NPC 死一个**")]
    public string 目标npcId = "";

    [Header("条件=到达")]
    public float 坐标X = 0f;
    public float 坐标Y = 0f;
    public float 坐标Z = 0f;
    [Min(0.5f)] public float 到达半径 = 3f;

    [Tooltip("条件=对话 时：要说完的那一段对话 id（留空 = 这个 NPC 的任意一段）")]
    public string 对话id = "";

    [Tooltip("条件=等待秒数 时：进这一阶段后等几秒算完成")]
    [Min(0f)] public float 等待秒 = 3f;

    [Tooltip("动作=走向/飞到 时的移动速度（米/秒）")]
    [Min(0.1f)] public float 动作速度 = 3.5f;

    [Tooltip("动作=镜头看目标/镜头回玩家 的过渡时长（秒）")]
    [Min(0.05f)] public float 镜头时长 = 1.2f;

    [Tooltip("动作=镜头看目标 时，镜头停在这个高度偏移上（米）")]
    public float 镜头高度 = 1.6f;

    [Header("条件（复用对话系统的标记机制）")]
    [Tooltip("需要全部具备这些标记，这个阶段才会被算作可接/可推进。分号分隔")]
    public string 需要标记 = "";

    [Tooltip("有其中任意一个标记就跳过这个阶段。分号分隔")]
    public string 排除标记 = "";

    [Header("任务状态标记（和对话系统打通的关键）")]
    [Tooltip("阶段被设为当前时加上的标记。分号分隔。对话表里「需要标记」写它，就能出现任务专属回答")]
    public string 接取加标记 = "";

    [Tooltip("阶段完成时加上的标记。分号分隔")]
    public string 完成加标记 = "";

    [Tooltip("**读档补齐用**：到达或越过这个阶段时，应当已经具备的标记（分号分隔）。" +
             "读档时按当前进度重放，把漏掉的标记补回来 —— 否则旧档会因为标记缺失而" +
             "掉进通用对话（实测：大师兄回话退到 dlg_common_01）")]
    public string 打标记 = "";

    [Header("奖励 / 调度")]
    [Tooltip("完成这个阶段发的物品，写法同「背包物品」列：物品id:数量|物品id:数量")]
    public string 奖励物品 = "";

    [Tooltip("完成这个阶段发的**宗门贡献**（0 = 不发）。和 `奖励物品` 互不影响，可以只发贡献")]
    [Min(0)] public int 奖励贡献 = 0;

    [Tooltip("这个阶段**开始时**对 NPC 做什么")]
    public 任务动作 动作 = 任务动作.无;

    [Tooltip("动作的目标 NPC：NpcDefinition.id")]
    public string 动作目标npcId = "";

    [Tooltip("动作参数：播动画时填动作名（如 swagger / angry_01 / walk / Yufeng_Forward）")]
    public string 动作参数 = "";

    [Header("演出（动作=播放对话 / 黑幕字幕 / 切换场景 用）")]
    [Tooltip("播放对话 / 黑幕字幕 的台词。黑幕字幕多行用 | 分隔")]
    [TextArea(2, 6)]
    public string 台词 = "";

    [Tooltip("动作=播放对话：谁在说。写「主角」= 玩家立绘放大并显示玩家名字")]
    public string 说话人 = "主角";

    [Tooltip("动作=播放对话：情绪名（震动 / 冒泡 / 发怒 / 害羞 / 惊讶，留空=不播）")]
    public string 情绪 = "";

    [Tooltip("动作=播放对话：情绪强度")]
    [Min(0f)] public float 情绪强度 = 1f;

    [Tooltip("动作=切换场景：目标场景名（如 Sect）")]
    public string 场景名 = "";

    [Header("黑幕外观（动作=黑幕字幕 / 移动玩家且黑幕 用）")]
    [Tooltip("**阶梯淡入的档数**。0 或空 = 用代码默认（24 档）。\n" +
             "★ 是「一帧一帧」的跳档，不是平滑渐变；档数 ÷ 黑幕字幕.淡步频(12) ≈ 秒数。\n" +
             "四幕「从此，一个平凡的少年踏上了修仙路」用 24 档 ≈ 2 秒。")]
    public int 淡入档数 = 0;

    [Tooltip("**阶梯淡出的档数**。0 或空 = 用代码默认（24 档）")]
    public int 淡出档数 = 0;

    [Tooltip("黑幕打字速度（字/秒）。0 或空 = 用 黑幕字幕 组件上的 每秒字数（默认 18）。\n" +
             "四幕那句放慢到 9 字/秒。")]
    public float 打字速度 = 0f;

    [Header("接取")]
    [Tooltip("勾上 = 进游戏就自动接这个任务（测试用最方便）")]
    public bool 自动接取 = false;

    [Tooltip("需要先完成这个任务id，才能接（留空 = 没有前置）")]
    public string 前置任务id = "";

    // ============================================================ 任务引导
    //
    // 这三列喂给 `任务引导.cs`（屏幕左侧的追踪面板 + 目标头顶的感叹号 + 屏幕外时的边缘箭头）。
    // 大部分阶段**不用填** —— 引导会按「条件」自动推：
    //   · 条件=对话/击杀/NPC到位 → 指向 `目标npcId` 那个 NPC
    //     （条件=对话 且 目标npcId 空 时，还会拿 `对话id` 去对话库里反查是哪个 NPC）
    //   · 条件=到达 → 指向 `坐标X/Y/Z`
    // 自动推不出来的（例如"去某某建筑走一趟""去某个传送门"）才需要填下面两列。

    [Header("任务引导（留空 = 按条件自动推）")]
    [Tooltip("引导指向哪个 NPC：`NpcDefinition.id`（如 npc_dashixiang）。\n" +
             "它在**当前场景**里才会出现头顶感叹号；不在本场景时面板只写「去找谁」")]
    public string 引导npcId = "";

    [Tooltip("引导指向哪个**地点**，写 `x;y;z`（例：`-4.59;3.48;29.92`）。**留空 = 没有地点目标**。\n" +
             "★ 分隔符用**分号**，别用半角逗号 —— CSV 是按逗号切列的，一个单元格里带逗号\n" +
             "会把后面所有列顶偏一格（实测踩过：整行错位、而且不报任何错）。\n" +
             "★ 为什么用字符串而不是 坐标X/Y/Z 那一组：坐标组拿 `(0,0,0)` 当**合法值**\n" +
             "（「到村口走一趟」的目标就是原点），没法用它区分「没填」和「填了原点」。\n" +
             "空串才是真正的「没填」 —— 这一列的语义只有「空」和「一个点」两种。")]
    public string 引导坐标 = "";

    [Tooltip("上面那个地点在面板里显示成什么（例：`宗门炼丹阁`）。留空 = 显示「目的地」")]
    public string 引导地点名 = "";

    [Tooltip("上面那个地点在**哪个场景**（例：`Sect`）。**留空 = 就是本场景**。\n" +
             "★ 填了它、而玩家不在那个场景时：**不画标记**（两个场景的坐标是两套空间，\n" +
             "拿宗门的坐标在洞府里画箭头会指到毫不相干的方向），面板改写成「目标：X（在「Sect」）」")]
    public string 引导场景 = "";

    /// <summary>引导坐标填了没（空串 = 没填；**解析得出来才算数**）</summary>
    public bool 有引导坐标 { get { Vector3 点; return 试解析引导坐标(out 点); } }

    /// <summary>
    /// 解析「x;y;z」。解析不出来返回 false（调用方按"没填"处理）。
    /// 分隔符**分号、逗号（半角/全角）、空格**都认 ——
    /// 表里请写分号（见上面的 Tooltip），其余几种是给手滑 / 从别处粘过来兜底的。
    /// </summary>
    public bool 试解析引导坐标(out Vector3 点)
    {
        点 = Vector3.zero;
        if (string.IsNullOrWhiteSpace(引导坐标)) return false;
        var 干净 = 引导坐标.Replace('；', ';').Replace('，', ',').Replace(',', ';').Replace('\t', ' ');
        var 段 = 干净.Split(new[] { ';', ' ' }, System.StringSplitOptions.RemoveEmptyEntries);
        if (段.Length < 3) return false;
        float x, y, z;
        if (!float.TryParse(段[0].Trim(), System.Globalization.NumberStyles.Float,
                            System.Globalization.CultureInfo.InvariantCulture, out x)) return false;
        if (!float.TryParse(段[1].Trim(), System.Globalization.NumberStyles.Float,
                            System.Globalization.CultureInfo.InvariantCulture, out y)) return false;
        if (!float.TryParse(段[2].Trim(), System.Globalization.NumberStyles.Float,
                            System.Globalization.CultureInfo.InvariantCulture, out z)) return false;
        点 = new Vector3(x, y, z);
        return true;
    }

    public Vector3 坐标 => new Vector3(坐标X, 坐标Y, 坐标Z);

    void OnValidate()
    {
        if (string.IsNullOrEmpty(id)) id = name;
        if (阶段 < 1) 阶段 = 1;
        if (数量 < 1) 数量 = 1;
    }
}
