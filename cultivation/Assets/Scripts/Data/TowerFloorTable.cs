using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// **镇妖塔的一段楼层配置**。
///
/// 1000 层如果一层一行，会生成 1000 份资产、也没法调 ——
/// 所以改成**分段**：一段覆盖一个楼层区间，段里指定「刷哪个组、等级怎么算」。
///
/// 用户定的映射是 `怪等级 = 层数 ÷ 10 向下取整 + 偏移`，
/// 那正好是 <see cref="起始层"/> 区间 + <see cref="每层等级步进"/> 的形式。
/// </summary>
[System.Serializable]
public class TowerSegment
{
    [Tooltip("本段覆盖的起始层（含）")]
    public int 起始层 = 1;

    [Tooltip("本段覆盖的结束层（含）")]
    public int 结束层 = 1000;

    [Tooltip("这一层刷哪个刷怪组（刷怪组表的 组id）")]
    public string 刷怪组 = "";

    [Tooltip("怪物等级的额外偏移。\n" +
             "基础等级 = (层数-1) ÷ 每多少层一级 + 起始等级，再 + 这个偏移")]
    public int 等级偏移 = 0;

    [Tooltip("这一段的怪物数量倍率（1 = 按刷怪组原样。用来做「后半段怪更多」）")]
    public float 数量倍率 = 1f;

    /// <summary>本段是否覆盖某层</summary>
    public bool 覆盖(int 层) => 层 >= 起始层 && 层 <= 结束层;
}

/// <summary>
/// **镇妖塔层表**：从 CSV「镇妖塔层表」生成。
///
/// ## 层 → 怪物等级
///
/// <code>
/// 怪等级 = 起始等级 + floor( (层数 - 1) / 每多少层一级 ) + 等级偏移 - 1
/// </code>
///
/// 默认 <c>每多少层一级 = 10</c>、<c>起始等级 = 1</c>，于是：
/// 第 1~10 层 → 1 级、第 11~20 层 → 2 级 …… 第 1000 层 → 101 级（夹到 100）。
///
/// > 严格按用户原话「层数 ÷ 10 向下取整」会得到 第 1~9 层 = 1 级、第 10 层 = 2 级 ——
/// > 那样第 10 层就跳级、每 10 层里有 9 层是同一级，台阶感是歪的。
/// > 这里改成上面那个式子，效果是**每 10 层整齐地跨一级**，若想还原原话把
/// > <c>起始等级</c> 设成 0 即可。
/// </summary>
[CreateAssetMenu(fileName = "TowerFloorTable_", menuName = "修仙/镇妖塔层表", order = 10)]
public class TowerFloorTable : ScriptableObject
{
    [Header("规模")]
    [Tooltip("塔一共多少层")]
    public int 总层数 = 1000;

    [Header("层 → 等级 的换算")]
    [Tooltip("每多少层提升一级")]
    public int 每多少层一级 = 10;

    [Tooltip("第 1 层对应的怪物等级（1 = 从 1 级怪开始）")]
    public int 起始等级 = 1;

    [Tooltip("怪物等级上限（补正表只有 100 级）")]
    public int 等级上限 = 100;

    [Header("★ 塔的数值曲线（用户 2026-10-01 重新定的口径）")]
    [Tooltip("**同一级内（= 同一个大境界的 10 层），从第 1 层到第 10 层怪一共变强多少倍。**\n\n" +
             "用户要求「这 10 层之间也要有由弱到强的递进」→ 默认 **×1.12**（每层约 +1.3%）。\n" +
             "1.0 = 关闭（这 10 层数值一样）\n\n" +
             "⚠️⚠️ **硬上限 ≈ ×1.38** —— 超过它第 11 层就会比第 10 层**弱**（倒挂）。\n" +
             "原因：玩家曲线一小境界只涨 **×1.38**（`累加倍率(11)/累加倍率(10)`），\n" +
             "而层内递进是**叠在**门槛之上的 —— 层内涨得比跨级还多，就必然倒挂。\n" +
             "实测 ×2.5 时每 10 层倒挂一次（99 处）。\n\n" +
             "想要「层内感觉更陡」的话，正路是**调大 `难度倍率`**（它整体抬升、不倒挂），\n" +
             "或者让**玩家一小境界涨更多**（改 `LevelCurve.每大境界倍率`），\n" +
             "而不是硬把层内递进拉大。")]
    [Range(1f, 1.38f)]
    public float 楼层内总量 = 1.12f;

    [Tooltip("**塔的难度倍率** —— 相对玩家同等级强度的倍数。\n\n" +
             "1.0 = 塔里的怪和玩家同级时一样强\n" +
             "1.33 = 怪比同级玩家强 33%（**默认**，会随层数缓慢变难一点）\n\n" +
             "因为这个倍率是**乘在整个曲线上**的，所以它会随层数一起放大：\n" +
             "第 10 层只强 33%，第 900 层就强很多倍 —— 这就是「卡玩家进度」的来源。")]
    [Min(0.1f)]
    public float 难度倍率 = 1.33f;

    /// <summary>
    /// **某一层怪的「总强度倍率」**（相对第 1 层）。
    ///
    /// <code>
    /// 等效等级 = (层 − 1) / 每多少层一级 + 起始等级
    /// 门槛     = LevelCurve.累加倍率(等效等级)        // ★ 和玩家功法**同一条曲线**
    /// 层内递进 = 楼层内总量 ^ (层在该级内的进度 0→1)
    /// 总倍率   = 门槛 × 层内递进 × 难度倍率
    /// </code>
    ///
    /// ## 为什么改成「和玩家同一条曲线」（用户 2026-10-01 纠正的口径）
    ///
    /// 用户原话：
    /// > 「我的理解是玩家每 10 级数值翻 20~50 倍，**对应塔就是每 100 层翻 20~50 倍**，
    /// > 可能更多一点，卡一下玩家的进度，但是你现在好像理解错误了」
    ///
    /// **老实现错在哪**：我原来用「每**大境界**（10 层）×25」推塔的倍率，
    /// 于是第 1000 层 = 25^100 ≈ 8.7e12 里还叠了 `每大境界倍率^大境界`，
    /// 而玩家的口径是「每 **10 级** ×25」⇒ 第 1000 层（等效 100 级）应该是 **25^10 量级**。
    /// 两者差了 **10 个数量级**，而且把 `float` 撑爆了（第 ~300 层就 `Infinity`）。
    ///
    /// **现在的口径**：
    /// · 玩家：每 10 级 ×25（`LevelCurve.累加倍率`）
    /// · 塔：**共用同一条曲线**（等效等级代入），并乘一个 <see cref="难度倍率"/>
    ///   ⇒ 第 100 层（等效 10 级）≈ ×25、第 901 层（等效 91 级）≈ ×2.8e12，
    ///   **和玩家同量级、始终略高一点**（不是指数级甩开）
    ///
    /// ## 单调性（为什么这次不会倒挂）
    ///
    /// `累加倍率(等效等级)` 本身对「层」单调，
    /// 而层内递进在跨级时归零、门槛前进一格（×25 量级）——
    /// ×25 ≫ 层内总量(×2)，所以**第 11 层必然强于第 10 层** ✓
    /// </summary>
    public float 取怪强度倍率(int 层)
    {
        层 = 夹层(层);
        int 步 = Mathf.Max(1, 每多少层一级);

        // 层 → 等效等级（可小数不用，只需整数级当门槛）
        int 大境界 = (层 - 1) / 步 + 1;
        float 等效等级 = 起始等级 + 大境界 - 1;

        // ★ 玩家曲线（同一份实现，不另抄一条）
        float 门槛 = LevelCurve.累加倍率(Mathf.Max(1f, 等效等级));

        // 层内递进：第 1 层 = 0（×1），第 `步` 层 = 1（×楼层内总量）
        int 序号 = (层 - 1) % 步;
        float 档内 = 步 > 1 ? 序号 / (float)(步 - 1) : 0f;
        float 递进 = Mathf.Pow(Mathf.Max(1f, 楼层内总量), 档内);

        return Mathf.Min(门槛 * 递进 * Mathf.Max(0.1f, 难度倍率), 强度倍率上限);
    }

    [Header("分段（由 CSV 生成）")]
    public List<TowerSegment> 分段 = new List<TowerSegment>();

    // ============================================================ 查询

    /// <summary>总层数安全值（至少 1）</summary>
    public int 有效总层数 => Mathf.Max(1, 总层数);

    /// <summary>把层数夹进 1~总层数</summary>
    public int 夹层(int 层) => Mathf.Clamp(层, 1, 有效总层数);

    /// <summary>
    /// **某一层怪的「总强度倍率」**（相对第 1 层）。
    ///
    /// <code>
    /// rank   = (该层等级 − 起始等级) / 每多少层一级          // 0, 0.1 … 1.0, 1.1 …（**连续**）
    /// 大境界 = floor(rank) + 1                              // 每满 1.0 一个大境界
    /// 层内   = rank − floor(rank)                           // 0 → 1
    /// 总倍率 = 每大境界倍率^(大境界−1) × 楼层内总量^层内
    /// </code>
    ///
    /// 第 1 层 = ×1.00；第 10 层 = ×楼层内总量；第 11 层 = ×每大境界倍率；第 101 层 = ×每大境界倍率² …
    ///
    /// ## 为什么必须用**同一个 rank** 推大境界和层内进度
    ///
    /// 我一开始用 `NpcLevelScale.等级到大境界(等级)` 算大境界（那个是 `(等级-1)/10+1`），
    /// 而层内进度用**全局**的 `(层-1) % 每多少层一级` —— 两者**坐标系不一致**：
    ///
    /// | 层 | 等级 | 等级到大境界 | 层内进度 | 结果 |
    /// |---|---|---|---|---|
    /// | 10 | 1 | 1 | 0.9（t=1） | ×1 × 2.5 = **×2.5** |
    /// | 11 | 2 | 1（**重置了**） | 0（t=0） | ×1 × 1 = **×1.0** ← 倒挂 |
    ///
    /// 因为 `等级到大境界(2)` 仍然是 1 ⇒ 大境界门槛没涨，而层内进度被打回 0。
    /// 每 10 层倒挂一次（实测 90 处）。
    ///
    /// **修法**：大境界直接从 rank 取整得到，和层内进度**共用同一个 rank**。
    /// 这样跨级时 `floor(rank)` 前进 1 ⇒ 门槛 ×25，层内进度回 0，**必然不回退** ✓
    ///
    /// ## 顺带的好处
    ///
    /// 因为强度不再经过补正表的档内曲线，攻击/防御/灵力的**组修正**
    /// （1.65/1.62/1.70）也就不再参与了 —— 所有属性统一乘同一个倍率。
    /// 补正表仍然负责「1 级基准」那一层（它的档位值就是 ×1），所以
    /// **改补正表的大境界倍率依然会整体生效**，只是档内形状不再影响塔。
    /// </summary>
    /// <summary>
    /// 强度倍率的**上限**，防 `float` 溢出成 `Infinity`。
    ///
    /// `float.MaxValue ≈ 3.4e38`，而 25^10 = 9.5e13、再乘层内 ×2.5 到第 1000 层约 2.4e14 …
    /// —— 等等，那是**倍率**，看起来还好。但塔里还有"数量倍率"、
    /// 以及怪本身的血量基准（1225）会一起乘上去：
    /// 实测第 ~450 层 `倍率 × 基准血量` 就已经顶到 `float` 上限，打印出 `Infinity`。
    ///
    /// 所以在这里封顶。封顶后高层之间**不再继续变强**（会重复），
    /// 但起码不会出现 `Infinity` 血量那种彻底坏掉的状态。
    ///
    /// > **根本问题**：1000 层 × 每大境界 ×25 的指数增长**装不进 `float`**。
    /// > 真要做到 1000 层，得把「每大境界倍率」调小、或者改 `double`、
    /// > 或者把塔的层数压到 100 层以内。见 docs/guides/镇妖塔.md §10。
    /// </summary>
    public const float 强度倍率上限 = 1e30f;

    /// <summary>
    /// **旧的"层内倍率"**（乘在补正结果上的那一份）。
    ///
    /// 现在**恒为 1** —— 强度已经全部由 <see cref="取怪强度倍率"/> 从零算出来，
    /// 补正表那条档内曲线不再参与。留着这个函数是为了让调用方少改，
    /// 也方便以后想恢复"补正表 + 层内微调"时有个挂点。
    /// </summary>
    public float 取楼层内倍率(int 层) => 1f;

    /// <summary>
    /// 某层的怪物等级（**整数，给玩家看 / 算击杀掉落用**）。
    ///
    /// 注意：同一级内的 10 层返回的**是同一个值** —— 数值上的递进见
    /// <see cref="取楼层内倍率"/>。
    /// </summary>
    public int 取怪物等级(int 层)
    {
        层 = 夹层(层);
        int 段 = 每多少层一级 > 0 ? 每多少层一级 : 10;
        int 基础 = 起始等级 + (层 - 1) / 段;
        int 偏移 = 取分段(层)?.等级偏移 ?? 0;
        return Mathf.Clamp(基础 + 偏移, 1, Mathf.Max(1, 等级上限));
    }

    /// <summary>某层用的分段（没命中就返回 null）</summary>
    public TowerSegment 取分段(int 层)
    {
        if (分段 == null) return null;
        for (int i = 0; i < 分段.Count; i++)
            if (分段[i] != null && 分段[i].覆盖(层)) return 分段[i];
        return null;
    }

    /// <summary>某层刷哪个组（没命中的段返回空串）</summary>
    public string 取刷怪组(int 层) => 取分段(层)?.刷怪组 ?? "";

    /// <summary>某层的数量倍率</summary>
    public float 取数量倍率(int 层)
    {
        var s = 取分段(层);
        return s != null ? Mathf.Max(0f, s.数量倍率) : 1f;
    }

    /// <summary>某层是不是 BOSS 层（每 10 层 = 大境界台阶）</summary>
    public bool 是台阶层(int 层) => 层 % Mathf.Max(1, 每多少层一级) == 0;

    /// <summary>这一层的等级在补正表里对应的「大境界」序号</summary>
    public static int 大境界(int 怪物等级) => NpcLevelScale.等级到大境界(怪物等级);
}
