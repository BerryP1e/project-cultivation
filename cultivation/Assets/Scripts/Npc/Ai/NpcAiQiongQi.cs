using UnityEngine;

/// <summary>
/// 穷奇（<c>NpcAiQiongQi</c>）—— 近战妖魔，共用逻辑全在 <see cref="近战妖魔Ai"/> 里，
/// 这里只填「这一只怪」量出来的数。
///
/// ### 判定方式：**武器网格实时求交**
/// 判定体 = <c>QiongQi_wuqi</c> 的网格（武器子物件，不是整个人）。
/// 武器扫到玩家**才算命中**，扫空就是漏招 —— 特效落在**接触点**。
///
/// 量出来的**接触窗**（把玩家摆在 1.9 米处，判定体真正和它相交的进度区间）：
///   · 普攻 Attack1：0.00f ~ 1.00f
///   · 神通 Attack2：0.00f ~ 1.00f
///
/// ### 量测值（菜单 修仙 / 怪物 / 量近战动作范围）
///   · 普攻 Attack1：峰值进度 0.76，前伸 2.60 米
///   · 神通 Attack2：峰值进度 0.64，前伸 2.86 米
///   · 站位 = min(2.60, 2.86) × 0.73 = **1.9 米**
/// 换模型 / 改动画之后**必须重新量**，别信手填。
///
/// 分工：`Attack1` 物理普通攻击（倍率 1，冷却 2.5s）；`Attack2` 物理主动神通（倍率 2，冷却 8s）；`Attack3` 不用。
/// </summary>
public class NpcAiQiongQi : 近战妖魔Ai
{
    protected override void 取默认参数()
    {
        // 判定体：武器子物件的网格（多个变体用 | 隔开，谁在就用谁）
        武器节点名 = "QiongQi_wuqi";

        // 接触窗（量出来的，不是猜的）
        普攻判定起 = 0.00f;  普攻判定止 = 1.00f;
        神通判定起 = 0.00f;  神通判定止 = 1.00f;

        普攻峰值进度 = 0.76f;
        普攻峰值前伸 = 2.60f;
        神通峰值进度 = 0.64f;
        神通峰值前伸 = 2.86f;

        // ★【穷奇专属补偿·实测】它的判定体 `QiongQi_wuqi` 是**蒙皮网格**，
        // 而 Unity 给蒙皮网格算的 `Renderer.bounds` **没有反映真实蒙皮范围**：
        // 运行时量到那个盒子只有 0.9×1.9×1.6 米、而且贴着身体（离玩家中心 1.2~2.4 米），
        // 而它**真实的**几何前伸是 2.60 米（量测工具手动蒙皮算出来的真值）。
        // 结果：站在 1.9 米**整场都碰不到玩家**（实测 8 秒 0 次接触、0 伤害）。
        // 外扩 0.8 米补上这个差值后 4/4 全中；1.2 米同样 4/4。
        // 这是**量出来的补偿**，不是拍的数：换模型/改动画要重新验。
        判定外扩 = 0.8f;

        // ★ 必须在赋完上面这些值之后再调 base —— 基类就是按它们去配招和定站位的
        base.取默认参数();
    }
}
