using UnityEngine;

/// <summary>
/// 箭魔（<c>NpcAiJianMo</c>）—— **射实体箭**的怪。
///
/// ### 弹体 = **动画里本来就有的那支箭**（用户 2026-09-29 的建议，改了做法）
/// 用户原话：「他射箭的动画中其实已经有了**箭这个组件**，但是动画结束这个箭就会消失掉，
/// 能否让动画结束了箭也不消失，**让它真正的飞出去**？来替代你现在生成箭的行为」
///
/// 做法（`飞弹妖魔Ai.动画弹体节点名`）：
///   1. 发射那一刻，**手动蒙皮**算出 `Object135`（就是动画里那支箭，蒙皮到 `Bone12`）
///      此刻的**真实世界中心**，用它当出生点；
///   2. 同时把模型里那支箭**藏起来**（= 它飞出去了）；
///   3. 飞出去的是烘好的静态网格副本 `特效/飞弹/专属/箭矢_Object135`，沿飞行方向飞；
///   4. 攻击结束再把模型里那支箭**放回来**（下次拉弓还要用）。
///
/// 好处：出生点**永远和动画里那支箭重合**，不再依赖"量出来的骨骼 + 偏移"去近似
/// （那些偏移还会随动作变化，a1/a2 得各量一套）。
///
/// ### 朝向
/// 用户也说清了：「**射击开始时的朝向就是射箭的正确方向，射击过程中的转体会让朝向和射箭方向偏离**」
/// —— 所以**不去把身体纠向玩家**（`攻击期间锁定朝向` 保持 true），让动作自己演；
/// 那支箭的位置和朝向都来自动画本身，自然就对得上。
///
/// 用户口述：a1 动画 **31%** 出箭、a2 动画 **57%** 出箭，都是**物理**伤害。
/// 共用逻辑在 <see cref="飞弹妖魔Ai"/> 里，这里只填「这一只怪」的数和量测值。
/// </summary>
public class NpcAiJianMo : 飞弹妖魔Ai
{
    protected override void 取默认参数()
    {
        站位距离 = 12f;
        飞弹速度 = 18f;
        消灭距离 = 22f;
        拦截层 = 0;

        // ---- 弹体：箭（Object135 烘出来的静态网格，箭尖已朝 +Z）----
        // 命中**留空** → 物理攻击自动兜基础命中特效（特效/命中/Hit_Physical）
        弹道路径 = "特效/飞弹/专属/箭矢_Object135";
        命中路径 = "";
        闪光路径 = "";

        // ★ 出生点 = **动画里那支箭此刻的位置**（`Object135` 蒙皮到 `Bone12`）
        动画弹体节点名 = "Object135";

        // 下面这两套「挂点 + 偏移」现在是**退路**（万一哪份模型里找不到 Object135 才会用）
        普攻挂点 = "Bone11";
        普攻挂点偏移 = new Vector3(0.266f, 0.375f, 0.450f);
        神通挂点 = "Bone11";
        神通挂点偏移 = new Vector3(0.289f, 0.671f, 0.380f);

        // ---- a1 普攻：动画 31% 出箭，**物理** ----
        普攻进度 = 0.31f;
        普攻属性 = DamageNature.物理;
        普攻冷却 = 3f;
        普攻弹体缩放 = 1f;

        // ---- a2 主动神通：动画 57% 出箭，**物理** ----
        有神通 = true;
        神通进度 = 0.57f;
        神通属性 = DamageNature.物理;
        神通冷却 = 8f;
        神通弹体缩放 = 1.25f;

        base.取默认参数();
    }
}
