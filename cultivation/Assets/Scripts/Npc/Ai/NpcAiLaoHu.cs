using UnityEngine;

/// <summary>
/// 老虎（<c>NpcAiLaoHu</c>）—— 近战妖魔，共用逻辑全在 <see cref="近战妖魔Ai"/> 里，
/// 这里只填「这一只怪」量出来的数。
///
/// ### 判定方式：**按动作范围**（没有武器可拿来求交）
/// 动画播到普攻 34% / 神通 42% 那一下结算，判定半径看 <c>攻击距离</c>。
/// 口径和白熊精 / 野猪一致。
///
/// ### 量测值（菜单 修仙 / 怪物 / 量近战动作范围）
///   · 普攻 Attack1：峰值进度 0.34，前伸 2.76 米
///   · 神通 Attack2：峰值进度 0.42，前伸 3.72 米
///   · 站位 = min(2.76, 3.72) × 0.73 = **2.0 米**
/// 换模型 / 改动画之后**必须重新量**，别信手填。
///
/// 分工：`Attack1` 物理普通攻击（倍率 1，冷却 2.5s）；`Attack2` 物理主动神通（倍率 2，冷却 8s）；`Attack3` 不用。
/// </summary>
public class NpcAiLaoHu : 近战妖魔Ai
{
    protected override void 取默认参数()
    {
        // 留空 = 没武器，走「按动作范围」判定
        武器节点名 = "";

        普攻峰值进度 = 0.34f;
        普攻峰值前伸 = 2.76f;
        神通峰值进度 = 0.42f;
        神通峰值前伸 = 3.72f;

        // ★ 必须在赋完上面这些值之后再调 base —— 基类就是按它们去配招和定站位的
        base.取默认参数();
    }
}
