using UnityEngine;

/// <summary>
/// **近战妖魔通用基类** —— 21 只"跟白熊精一样"的怪共用它，子类只填自己的数。
///
/// | 招 | 动画 | 类别 | 属性 | 倍率 | 冷却 |
/// |---|---|---|---|---|---|
/// | 普攻 | `Attack1` | 普通攻击 | **物理** | 1.0 | 2.5 秒 |
/// | 主动神通 | `Attack2` | 主动神通 | **物理** | 2.0 | **8 秒**（用户 2026-09-29 定） |
/// | — | `Attack3` | 不用 | | | |
///
/// ### 两种判定方式（用户 2026-09-29 定）
/// 1. **有武器的怪**（`武器节点名` 填了）→ **网格判定**：
///    攻击期间逐帧拿**武器子物件的网格**和玩家求交，**碰到了才出伤**，特效落在接触点。
///    没碰到 = 这 ↓ 打空（漏招）。
/// 2. **没武器的怪**（`武器节点名` 留空）→ **按动作范围**：动画放到 `峰值进度` 那一下结算
///    （白熊精/野猪那套老口径）。
///
/// ### 这些数字是怎么来的
/// **不是手填的**，是菜单 **修仙 / 怪物 / 量近战动作范围** 逐帧采样量出来的
/// （工具会用白熊精当标定样本：它的真值 3.44@0.52 / 4.01@0.78 是手量过的）。
/// 换模型 / 改动画之后**要重新量**。
///
/// ### 站位 = 观感口径
/// `攻击距离 = min(普攻峰值前伸, 神通峰值前伸) × 0.73`。
/// 0.73 来自白熊精：武器最远 3.44 米 → 站位 2.5 米。
/// **别按"判定够得着"定站位** —— 那样武器尖只是刚够到人，看着像打空。
///
/// ### 网格判定的"出手进度"是一段**窗口**
/// 打到峰值那一刻才开窗就太晚了（武器只在峰值那一帧最远），所以要开一段区间：
///   · `普攻判定起/止`、`神通判定起/止` = 量测工具量出来的**真实接触窗**
///     （把玩家盒子摆在站位上，看判定体哪几帧真的和它相交）
///   · **别用「峰值 ± 一个猜的偏移」** —— 穷奇就是这么漏招的（实测 9 秒里一次都没碰到）
/// 进度式判定（没武器）则仍然**就取峰值那一帧**。
/// </summary>
public class 近战妖魔Ai : NpcAiDemon
{
    [Header("近战 · 共用数值")]
    [Tooltip("普攻（Attack1）冷却（秒）")]
    public float 普攻冷却 = 2.5f;

    [Tooltip("主动神通（Attack2）冷却（秒）—— **用户 2026-09-29 统一定 8 秒**")]
    public float 神通冷却 = 8f;

    [Tooltip("普攻倍率")]
    public float 普攻倍率 = 1f;

    [Tooltip("主动神通倍率")]
    public float 神通倍率 = 2f;

    [Header("动作范围（自动量测，改动画后要重新量）")]
    [Tooltip("普攻「判定体最前伸」出现在动画的百分之多少")]
    [Range(0.05f, 0.95f)] public float 普攻峰值进度 = 0.50f;

    [Tooltip("普攻最前伸多少米（用来定站位）")]
    public float 普攻峰值前伸 = 2.5f;

    [Tooltip("神通「判定体最前伸」出现在动画的百分之多少")]
    [Range(0.05f, 0.95f)] public float 神通峰值进度 = 0.50f;

    [Tooltip("神通最前伸多少米")]
    public float 神通峰值前伸 = 3f;

    [Header("判定体")]
    [Tooltip("★ 武器子物件名（可以填多个，用 `|` 隔开）。\n" +
             "**填了 = 用它的网格做实时判定**；留空 = 没武器的怪，按动作范围（动画进度）判。")]
    public string 武器节点名 = "";

    [Header("接触窗（网格判定用 —— 必须用「量近战动作范围」量出来，别手填）")]
    [Tooltip("普攻：判定体**真正扫到玩家**的进度区间。\n" +
             "**起点填 -1 = 没量过**，退回「峰值 ± 偏移」推算（猜的，容易漏招）。")]
    public float 普攻判定起 = -1f;

    [Tooltip("普攻：接触窗终点")]
    public float 普攻判定止 = -1f;

    [Tooltip("主动神通：判定体真正扫到玩家的进度区间起点（-1 = 没量过）")]
    public float 神通判定起 = -1f;

    [Tooltip("主动神通：接触窗终点")]
    public float 神通判定止 = -1f;

    [Tooltip("没量过接触窗时的退路：窗口比峰值**提前**多少开")]
    public float 开窗提前 = 0.10f;

    [Tooltip("没量过接触窗时的退路：窗口比峰值**延后**多少关")]
    public float 关窗延后 = 0.12f;

    [Tooltip("把判定包围盒往外扩多少米")]
    public float 判定外扩 = 0.15f;

    [Header("命中特效")]
    [Tooltip("普攻留空 = 自动用 NpcAiBase.物理基础命中特效（FX/Hit_Physical）")]
    public string 普攻命中特效 = "";

    [Tooltip("主动神通用的【更重的】命中特效")]
    public string 重击命中特效 = "特效/命中/Hit_Physical_Heavy";

    /// <summary>这一只怪是不是走网格判定</summary>
    protected bool 用武器网格 => !string.IsNullOrEmpty(武器节点名);

    [Header("招式开关")]
    [Tooltip("要不要主动神通（a2）。关掉就只出普攻（例：冥妖用户只要 a1）")]
    public bool 有神通 = true;

    protected override void 取默认参数()
    {
        确保攻击方式();          // ★ 先保证三条默认招式在（Awake 没跑过时也不会静默早退）
        base.取默认参数();

        索敌范围 = 14f;
        脱战范围 = 22f;
        攻击间隔倍率 = 1.3f;
        转向速度 = 420f;
        奔跑倍率 = 1f;

        // 站位 = 「两种招式里**较短的那个**前伸」× 0.73 ——
        // 取短的才能保证**两招的武器都能从玩家身上扫过去**（取长的会让短招打空气）。
        攻击距离 = Mathf.Max(1.2f, Mathf.Min(普攻峰值前伸, 有神通 ? 神通峰值前伸 : 普攻峰值前伸) * 0.73f);

        if (攻击方式 == null || 攻击方式.Length < 2) return;
        布一招(攻击方式[0], "Attack1", AttackKind.普通攻击, 普攻倍率, 普攻冷却,
               普攻峰值进度, 普攻判定起, 普攻判定止, 普攻命中特效, 1f);
        if (有神通)
            布一招(攻击方式[1], "Attack2", AttackKind.主动神通, 神通倍率, 神通冷却,
                   神通峰值进度, 神通判定起, 神通判定止, 重击命中特效, 1.15f);
        else
            攻击方式[1].动作名 = "";

        // Attack3 不用
        攻击方式[2].动作名 = "";
    }

    /// <summary>把一招配好</summary>
    void 布一招(NpcAttackConfig 招, string 动作, AttackKind 类别, float 倍率, float 冷却,
                 float 峰值进度, float 判定起, float 判定止, string 命中特效, float 特效缩放)
    {
        招.动作名 = 动作;
        招.是施法 = false;                       // 近战，没有飞弹
        招.伤害属性 = DamageNature.物理;          // 用户：这些全是物理
        招.攻击类别 = 类别;
        招.技能倍率 = 倍率;
        招.冷却 = 冷却;
        招.命中特效路径 = 命中特效;
        招.命中特效缩放 = 特效缩放;

        招.用网格判定 = 用武器网格;
        招.判定网格名 = 武器节点名;
        招.判定外扩 = 判定外扩;
        if (用武器网格)
        {
            // 网格判定：在这一段进度里逐帧拿武器网格碰玩家，**碰到的那一帧**才出伤。
            // 窗口 = 量测工具量出来的「判定体真正扫到玩家」的区间；
            // 没量过（判定起 < 0）才退回「峰值 ± 偏移」推算。
            if (判定起 >= 0f)
            {
                招.出手进度 = Mathf.Clamp(判定起, 0f, 0.95f);
                招.判定结束进度 = Mathf.Clamp(判定止 >= 0f ? 判定止 : 峰值进度 + 关窗延后, 0.05f, 0.99f);
            }
            else
            {
                招.出手进度 = Mathf.Clamp(峰值进度 - 开窗提前, 0.10f, 0.90f);
                招.判定结束进度 = Mathf.Clamp(峰值进度 + 关窗延后, 0.20f, 0.98f);
            }
        }
        else
        {
            // 动作范围：就到峰值那一帧结算（白熊精口径）
            招.出手进度 = 峰值进度;
            招.判定结束进度 = 0.98f;
        }

        清掉飞弹配置(招);
    }

    /// <summary>把**飞弹专属**的配置清干净（命中特效不是飞弹专属，不能清 —— 白熊精那边踩过）</summary>
    static void 清掉飞弹配置(NpcAttackConfig 配置)
    {
        配置.子弹特效路径 = "";
        配置.闪光特效路径 = "";
    }

    // ---- ASCII 别名 ----
    public float BasicCooldown => 普攻冷却;
    public float SkillCooldown => 神通冷却;
    public float AttackReach => 攻击距离;
    public bool UsesWeaponMesh => 用武器网格;
}
