using UnityEngine;

/// <summary>
/// 玄蜂（<c>NpcAiXuanFeng</c>）—— **从尾巴射箭**的怪。
///
/// 弹体用「Object135」（烘成静态网格 → `特效/飞弹/专属/箭矢_Object135`），长轴已对准 **+Z**，
/// 所以 `NpcProjectile` 让它朝飞行方向时**箭尖正对目标**。
/// 用户口述：a1 动画 **46.5%** 从**尾部（模型末端）**发射（**物理**）；**没有 a2**。
///
/// ### 出生点：挂 `Bone13`（**不是**量出来的"最近骨骼"）
/// 【坑·已修】第一版是用量测工具算的「模型最靠后的顶点 → 离它最近的骨骼」，
/// 得到 `Bone04 + (-0.549, 0.380, 0.899)` —— **离屁股 1.83 米**（在身体中上部）。
/// 用户一眼看出来："**玄蜂的箭不是从屁股射出来的**"。
///
/// **正确做法**：屁股那个顶点是**蒙皮在哪根骨头上**，就挂那根骨头 —— 实测最靠后的 8 个顶点
/// **100% 权重**都在 `Bone13` / `Bone13(mirrored)` 上（左右各一半）。
/// 权重 1.0 意味着偏移在骨骼空间里是**刚性**的，**任何姿势下都精确贴在屁股上**
/// （实测回算误差 0.0000 米，改后出膛点离屁股 **0.001 米**）。
///
/// > 教训：找"某块肉该挂哪根骨"，**看蒙皮权重**，别用"离得最近的骨骼"猜。
/// > 量测工具也已经改成这个算法（见 `飞弹出生点量测.最近骨骼`）。
/// </summary>
public class NpcAiXuanFeng : 飞弹妖魔Ai
{
    protected override void 取默认参数()
    {
        站位距离 = 12f;
        飞弹速度 = 18f;
        消灭距离 = 22f;
        拦截层 = 0;

        // ---- 弹体：箭（Object135 烘出来的静态网格，箭尖已朝 +Z）----
        // 命中**留空** → 物理攻击自动兜基础命中特效（特效/命中/Hit_Physical）
        弹道路径 = "特效/飞弹/专属/箭矢_Object135";
        命中路径 = "";
        闪光路径 = "";

        // ---- a1 普攻：动画 46.5% 从**屁股**出箭，**物理** ----
        // 屁股顶点 100% 蒙皮在 Bone13 / Bone13(mirrored) 上，所以挂 Bone13 + 这一小段偏移
        // = 精确落在屁股中心（换取任何姿势都成立）
        普攻挂点 = "Bone13";
        普攻挂点偏移 = new Vector3(0.038f, -0.339f, 0.081f);
        普攻进度 = 0.465f;
        普攻属性 = DamageNature.物理;
        普攻冷却 = 3f;
        普攻弹体缩放 = 1f;

        // 用户只给了 a1：神通关掉
        有神通 = false;

        base.取默认参数();
    }
}
