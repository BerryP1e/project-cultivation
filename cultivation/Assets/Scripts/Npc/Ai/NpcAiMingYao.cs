using UnityEngine;

/// <summary>
/// 冥妖（<c>NpcAiMingYao</c>）—— 近战妖魔，**只出 a1**。
///
/// 用户口述：「基本和白熊精的 ai 一样，a1 普攻，注意观察 a1 的动作范围来做伤害判定。」
/// —— 只提了 a1，所以 a2 主动神通**关掉**（`有神通 = false`）。
/// 它的控制器里其实有 Attack2/Attack3 片段，哪天真要给它加神通，把 `有神通` 打开、
/// 再按量测填 `神通峰值进度 / 神通峰值前伸` 就行。
///
/// 量测（菜单 修仙 / 怪物 / 量近战动作范围）：
///   · 普攻 Attack1：峰值 **0.40**，前伸 **1.97** 米
///   · 站位 = 1.97 × 0.73 ≈ **1.4 米**
///
/// > ⚠️ 冥妖的 **FBX 和 prefab 同名同目录**（`MingYao_01.FBX` + `MingYao_01.prefab`），
/// > 用 `Resources.Load` 按路径取**可能拿到 FBX**（那份没有控制器、没有 AI、不会动）。
/// > 写探针时要按文件夹取、挑**带 `NpcInstance`** 的那个。
/// </summary>
public class NpcAiMingYao : 近战妖魔Ai
{
    protected override void 取默认参数()
    {
        武器节点名 = "";              // 没武器 → 按动作范围判定

        普攻峰值进度 = 0.40f;
        普攻峰值前伸 = 1.97f;

        // 量测值先留着（以后要加神通直接把 有神通 打开）
        神通峰值进度 = 0.54f;
        神通峰值前伸 = 1.23f;

        有神通 = false;               // 用户只要 a1

        base.取默认参数();
    }
}
