using UnityEngine;

/// <summary>
/// 蜘蛛精（<c>NpcAiZhiZhuJing</c>）—— **近战 + 飞弹混着用**的怪，两个基类的活儿它都要。
///
/// 用户口述：
///   · a1 普攻：**近战**，按动作范围判定（`近战妖魔Ai` 那套口径）
///   · a2 主动神通：动画 **77%** 从**尾部（模型末端）**发射飞弹，**特殊**伤害
///
/// 飞弹 5 要素（见 <see cref="飞弹妖魔Ai"/>）：出生点 = `Bip01 Tail3` + 量出来的偏移；
/// 直线匀速不追踪；不被场景阻挡、可被神通/法宝/灵阵拦；飞出 22 米淡化消散。
/// 特效主题 **Dark_Magic**（紫色妖术）—— 库里没有"蛛毒"主题，按颜色挑了最像妖术的一套。
///
/// ### 混合怪的**关键**：两招必须设距离门槛
/// a1（近战）在远处根本够不着，a2（飞弹）在贴身时没必要放。
/// 不设门槛的话 `可用出手方式()` 是**随机挑**的 —— 它会站在 12 米外随机挑到近战动作砍空气。
/// 所以：a1 只在 ≤3.5 米出，a2 只在 ≥3.0 米出（中间留 0.5 米重叠，免得出现"两招都不能出"的空档）。
/// </summary>
public class NpcAiZhiZhuJing : 飞弹妖魔Ai
{
    protected override void 取默认参数()
    {
        站位距离 = 12f;
        飞弹速度 = 18f;
        消灭距离 = 22f;
        拦截层 = 0;

        // ---- 飞弹特效三件套（主题 Dark_Magic）----
        弹道路径 = 飞弹库 + 弹道子目录 + "Dark_Magic_Projectile_Only";
        命中路径 = 飞弹库 + 命中的子目录 + "Dark_Magic_Impact";
        闪光路径 = 飞弹库 + 闪光子目录 + "Dark_Magic_Flash";

        // ---- a1：近战横扫（按动作范围判定，不用网格）----
        普攻是近战 = true;
        普攻最大出手距离 = 3.5f;              // 远了不出这一招
        普攻近战峰值 = 0.56f;                 // 量测：Attack1 前伸最远在 56%
        普攻近战前伸 = 2.20f;                 // 量测：2.20 米
        普攻倍率 = 1f;
        普攻冷却 = 2.5f;

        // ---- a2：从尾部吐毒/妖术（动画 77%）----
        有神通 = true;
        神通最小出手距离 = 3.0f;              // 太近就不丢飞弹
        神通挂点 = "Bip01 Tail3";              // 尾部（模型末端）
        神通挂点偏移 = new Vector3(0.222f, 0.437f, -0.010f);   // 量出来的
        神通进度 = 0.77f;                      // 用户口述：动画 77%
        神通属性 = DamageNature.特殊;
        神通倍率 = 2.2f;
        神通冷却 = 8f;

        base.取默认参数();
    }
}
