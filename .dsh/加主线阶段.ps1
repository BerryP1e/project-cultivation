function 造行($map) {
    $l = New-Object System.Collections.Generic.List[string]
    foreach ($名 in $列序) { if ($map.ContainsKey($名)) { $l.Add([string]$map[$名]) } else { $l.Add('') } }
    return ($l -join ',')
}
function 拆行($line) {
    $f = $line.Split(',')
    $l = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $列序.Count; $i++) { if ($i -lt $f.Length) { $l.Add($f[$i]) } else { $l.Add('') } }
    return $l
}

